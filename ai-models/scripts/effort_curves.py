#!/usr/bin/env python3
"""Offline effort curves per model family from favorites.snapshot.json -> EFFORTS.md."""
import json
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent / "data" / "2026-09-30"
ORDER = ["low", "medium", "high", "xhigh", "max"]
FAMILIES = [  # registry aliases with three or more effort levels
    ("haiku", "Claude Haiku 5.5"),
    ("sonnet", "Claude Sonnet 5.5"),
    ("opus", "Claude Opus 5.5"),
    ("sol", "GPT-6.1 Sol"),
    ("luna", "GPT-6 Luna"),
    ("luna-5-6", "GPT-5.6 Luna"),
]


def fmt(v, nd=1, suffix=""):
    return "N/A" if v is None else f"{v:,.{nd}f}{suffix}"


def pct(b, key):
    v = b[key]["percent"]
    return None if v is None else v


def main():
    root = DIR.parent.parent
    registry = json.loads((root / "favorites.json").read_text())["models"]
    snap = {m["slug"]: m for m in json.loads((DIR / "favorites.snapshot.json").read_text())["models"]}
    out = """---
doc_type: reference
updated_at: 2026-10-07
purpose: Generated effort curves per model family, with the cost of each extra index point.
related:
  - path: ./favorites.snapshot.json
    why: Machine-readable source of these numbers.
  - path: ../../EFFORTS.md
    why: The written guide that interprets these curves.
  - path: ../../scripts/effort_curves.py
    why: Script that generates this file.
---

# Effort curves

Generated by `scripts/effort_curves.py`; do not edit numbers here.

- Extra point cost = extra USD per task divided by extra Intelligence Index points
  versus the effort below. It shows where paying for more thinking stops being
  worth it. N/A means a value is missing, not zero.
- Wait = median time to the first visible token on the benchmark prompts.
  Claude thinking is hidden by default, so this grows fast with effort.
- Decode s/task is a weighted decode estimate, not wall-clock completion.
- Rows marked * come from the website-only capture of 2026-10-07 (no API
  cross-check). Unmarked rows are the 2026-09-30 API-checked rows.
- Hallucination = share of wrong answers that were guesses; lower is safer.
"""
    for alias, title in FAMILIES:
        configs = sorted(registry[alias]["configurations"], key=lambda c: ORDER.index(c["effort"]))
        out += f"\n## {title}\n\n"
        out += ("| Effort | Intelligence | USD/task | Extra point cost | Output tokens/task | Decode s/task | Wait s | "
                "Tokens/s | Terminal-Bench | AutomationBench | GDP.pdf | AA-LCR | Hallucination | Omniscience | Briefcase Elo |\n")
        out += "|---|" + "---:|" * 14 + "\n"
        prev = None
        for c in configs:
            m = snap[c["slug"]]
            h, w = m["headline"], m["website"]
            b = w["benchmark_scores"]
            ii, cost = h["intelligence_index"], h["intelligence_index_cost_per_task_usd"]
            extra = None
            if prev and None not in (ii, cost, prev[0], prev[1]) and ii > prev[0]:
                extra = (cost - prev[1]) / (ii - prev[0])
            tokens = (w["intelligence_index_output_tokens_per_task"] or {}).get("output")
            hall = w["omniscience_hallucination_fraction_of_noncorrect_responses"]
            star = "" if h["source"] == "api" else "*"
            out += "| " + " | ".join([
                c["effort"] + star, fmt(ii), fmt(cost, 3), fmt(extra, 3),
                fmt(tokens and tokens / 1000, 0, "K"), fmt(w["intelligence_index_decode_time_per_task_seconds"], 0),
                fmt(h["median_time_to_first_token_seconds"], 1), fmt(h["median_output_tokens_per_second"], 0),
                fmt(pct(b, "terminalbench-4-0"), 1, "%"), fmt(pct(b, "automationbench-aa"), 1, "%"),
                fmt(pct(b, "gdp-pdf"), 1, "%"), fmt(pct(b, "aa-lcr-v1-1"), 1, "%"),
                fmt(hall and hall * 100, 1, "%"), fmt(b["aa-omniscience"]["raw"]), fmt(b["aa-briefcase"]["raw"], 0),
            ]) + " |\n"
            prev = (ii, cost)
    (DIR / "EFFORTS.md").write_text(out)
    print("families", len(FAMILIES))


main()
